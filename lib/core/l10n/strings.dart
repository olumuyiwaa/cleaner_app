/// Tiny dictionary-based translations (English and Dutch).
///
/// Use `context.t('key')` or `context.t('key', {'name': 'Anna'})`; `{name}`
/// placeholders in the text are replaced. A missing Dutch string falls back
/// to English, and a missing English one shows the key itself so it is easy
/// to spot.
String trFor(String lang, String key, [Map<String, String>? args]) {
  var text = (lang == 'nl' ? _nl[key] : null) ?? _en[key] ?? key;
  if (args != null) {
    args.forEach((k, v) => text = text.replaceAll('{$k}', v));
  }
  return text;
}

extension TranslateContext on BuildContext {
  String t(String key, [Map<String, String>? args]) =>
      trFor(Localizations.localeOf(this).languageCode, key, args);
}

